"""
Feature Engineering Module
Handles the creation of time-based features, rolling averages, 
lagged features, and interaction terms.
"""

import pandas as pd

def create_time_features(df):
    """Extracts hour, day of week, month, weekday indicators, etc. directly from the index."""
    df = df.copy()
    df['hour'] = df.index.hour
    df['day_of_week'] = df.index.dayofweek
    df['month'] = df.index.month
    
    # 0-4 are Monday-Friday, 5-6 are Saturday-Sunday
    df['is_weekend'] = df.index.dayofweek.isin([5, 6]).astype(int)
    
    return df

def create_rolling_features(df, target_col='Appliances', windows=[6, 18]): 
    """
    Computes rolling averages to smooth trends.
    Since data is in 10 min intervals: window=6 is 1 hour, window=18 is 3 hours.
    """
    df = df.copy()
    for w in windows:
        # shift(1) ensures we don't include the current timestamp (prevent data leakage)
        df[f'{target_col}_roll_mean_{w}'] = df[target_col].shift(1).rolling(window=w).mean()
        df[f'{target_col}_roll_std_{w}'] = df[target_col].shift(1).rolling(window=w).std()
    
    return df

def create_lagged_features(df, target_col='Appliances', lags=[1, 3, 6]):
    """
    Creates lagged features using past values.
    lag=1 (10 mins ago), lag=3 (30 mins ago), lag=6 (1 hour ago)
    """
    df = df.copy()
    for lag in lags:
        df[f'{target_col}_lag_{lag}'] = df[target_col].shift(lag)
        
    return df

def create_interaction_features(df):
    """Generates interaction terms between highly correlated features."""
    df = df.copy()
    # the difference between indoor and outdoor temperature affects heating/cooling
    if 'T1' in df.columns and 'T_out' in df.columns:
        df['Temp_diff_indoor_outdoor'] = df['T1'] - df['T_out']
    
    return df

def feature_selection(df, target_col='Appliances'):
    """
    Selects the most predictive features. For deep learning, we often keep most, 
    but we must drop rows with NaN values generated by the lag/rolling functions.
    """
    # Lagging and rolling creates NaNs at the very beginning of the dataset
    df = df.dropna()
    
    # TODO: In version 2.0, consider integrating external API data for public holidays 
    # as that might improve weekend/holiday energy prediction accuracy.
    return df

